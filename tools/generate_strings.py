#!/usr/bin/env python3
"""Writes SleepFlow's .strings files from tools/strings_da.py.

  python3 tools/generate_strings.py

Danish UI strings go to App/Resources/da.lproj/Localizable.strings. English needs no table:
the English source text is the key. Permission texts go to <lang>.lproj/InfoPlist.strings.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from strings_da import DA  # noqa: E402

RESOURCES = os.path.join(HERE, "..", "App", "Resources")

INFO_PLIST = {
    "en": {
        "CFBundleDisplayName": "SleepFlow",
        "NSMicrophoneUsageDescription": "SleepFlow listens for snoring, coughing, sleep talking and movement while you sleep. The sound is analysed on your iPhone and never uploaded.",
        "NSAlarmKitUsageDescription": "SleepFlow schedules your wake-up alarm so it rings even when the phone is locked or in Silent mode.",
        "NSMotionUsageDescription": "SleepFlow uses the motion sensor to notice how you move during the night when the phone lies on the mattress.",
    },
    "da": {
        "CFBundleDisplayName": "SleepFlow",
        "NSMicrophoneUsageDescription": "SleepFlow lytter efter snorken, hoste, søvnsnak og bevægelse, mens du sover. Lyden analyseres på din iPhone og bliver aldrig uploadet.",
        "NSAlarmKitUsageDescription": "SleepFlow sætter din vækkealarm, så den ringer, selv når telefonen er låst eller på lydløs.",
        "NSMotionUsageDescription": "SleepFlow bruger bevægelsessensoren til at registrere, hvordan du bevæger dig om natten, når telefonen ligger på madrassen.",
    },
}

SPECIFIER = re.compile(r"%(?:\d+\$)?(?:lld|ld|d|@|lf|f)")
STRAY_PERCENT = re.compile(r"%(?!(?:\d+\$)?(?:lld|ld|d|@|lf|f))")


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def check(table):
    problems = []
    for key, value in table.items():
        if sorted(SPECIFIER.findall(key)) != sorted(SPECIFIER.findall(value)):
            problems.append(f"specifiers differ: {key!r} -> {value!r}")
        if STRAY_PERCENT.search(SPECIFIER.sub("", value)):
            problems.append(f"stray % in value: {value!r}")
        if not value.strip():
            problems.append(f"empty value: {key!r}")
        if key != key.strip():
            problems.append(f"key with surrounding spaces: {key!r}")
    return problems


def write(path, header, table):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    lines = [f"/* {header} Generated by tools/generate_strings.py – edit tools/strings_da.py instead. */", ""]
    for key in sorted(table, key=lambda k: (k.lower(), k)):
        lines.append(f'"{escape(key)}" = "{escape(table[key])}";')
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


def main():
    problems = check(DA)
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    write(os.path.join(RESOURCES, "da.lproj", "Localizable.strings"), "SleepFlow – Danish.", DA)
    for language, table in INFO_PLIST.items():
        write(os.path.join(RESOURCES, f"{language}.lproj", "InfoPlist.strings"), f"SleepFlow – permission texts ({language}).", table)
    print(f"Danish entries: {len(DA)}")


if __name__ == "__main__":
    main()
